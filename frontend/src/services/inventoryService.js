const INVENTORY_STORAGE_KEY = 'nexus_inventory_items'
const DISPATCH_STORAGE_KEY = 'nexus_dispatch_orders'
export const INVENTORY_UPDATED_EVENT = 'nexus:inventory-updated'

function notifyInventoryUpdated() {
  if (typeof window !== 'undefined' && typeof window.dispatchEvent === 'function') {
    window.dispatchEvent(new CustomEvent(INVENTORY_UPDATED_EVENT))
  }
}

export function subscribeInventoryUpdated(callback) {
  if (typeof window === 'undefined' || typeof window.addEventListener !== 'function') {
    return () => {}
  }
  const handleCustom = () => callback()
  const handleStorage = (event) => {
    if (
      !event ||
      event.key === null ||
      event.key === INVENTORY_STORAGE_KEY ||
      event.key === DISPATCH_STORAGE_KEY
    ) {
      callback()
    }
  }
  window.addEventListener(INVENTORY_UPDATED_EVENT, handleCustom)
  window.addEventListener('storage', handleStorage)
  return () => {
    window.removeEventListener(INVENTORY_UPDATED_EVENT, handleCustom)
    window.removeEventListener('storage', handleStorage)
  }
}

export function mapHardwareCategoryToServiceType(category, explicitServiceType = '') {
  const explicit = String(explicitServiceType || '').trim().toUpperCase()
  if (explicit === 'BROADBAND') return 'BROADBAND'
  if (explicit === 'DIALUP' || explicit === 'DIAL_UP' || explicit === 'LEASED_LINE') {
    return 'DIAL_UP'
  }
  if (explicit === 'LANDLINE' || explicit === 'SIP_TRUNK') return 'LANDLINE'

  const cat = String(category || '').trim().toUpperCase()
  if (cat === 'ONT' || cat === 'FTTH' || cat === 'BROADBAND') return 'BROADBAND'
  if (
    cat === 'MODEM' ||
    cat === 'ROUTER' ||
    cat === 'DIAL_UP' ||
    cat === 'DIALUP' ||
    cat === 'LEASED_LINE'
  ) {
    return 'DIAL_UP'
  }
  if (cat === 'VOIP' || cat === 'SBC' || cat === 'LANDLINE' || cat === 'SIP_TRUNK') {
    return 'LANDLINE'
  }
  return 'BROADBAND'
}

export function normalizeInventoryRecord(item = {}) {
  const resolvedId = String(item.id || item.serialNumber || `EQ-${Date.now().toString().slice(-6)}`).trim()
  const serialNumber = String(item.serialNumber || resolvedId).trim().toUpperCase()
  const macAddress = String(item.macAddress || '').trim().toUpperCase()
  const category = String(item.category || 'ONT').trim().toUpperCase()
  const serviceType = mapHardwareCategoryToServiceType(category, item.serviceType)
  const status = String(item.status || 'IN_STOCK').trim().toUpperCase()
  const rawCustomer =
    item.assignedCustomer ||
    (item.customerName && item.customerName !== 'Unassigned (-)' ? item.customerName : null)

  return {
    ...item,
    id: resolvedId,
    serialNumber,
    macAddress,
    category,
    serviceType,
    vendor: String(item.vendor || item.ouiVendor || 'Nexus Certified Vendor').trim(),
    ouiVendor: String(item.ouiVendor || item.vendor || 'Nexus Certified Vendor').trim(),
    ports: String(item.ports || item.specs || 'Standard Carrier Interface').trim(),
    specs: String(item.specs || item.ports || 'Standard Carrier Interface').trim(),
    firmware: String(item.firmware || 'NX-FW-v4.8.2').trim(),
    status,
    contractAccount: item.contractAccount || null,
    assignedOrderId: item.assignedOrderId || null,
    assignedCustomer: rawCustomer || null,
    customerName: item.customerName || rawCustomer || 'Unassigned (-)',
  }
}

export function isInventoryDeviceAvailable(item) {
  if (!item) return false
  const normalized = normalizeInventoryRecord(item)
  return (
    normalized.status === 'IN_STOCK' &&
    !normalized.assignedOrderId &&
    !normalized.contractAccount
  )
}

export function fetchInventoryRecords() {
  const raw = localStorage.getItem(INVENTORY_STORAGE_KEY)
  if (raw !== null) {
    try {
      const parsed = JSON.parse(raw)
      if (Array.isArray(parsed)) {
        return parsed.map(normalizeInventoryRecord)
      }
    } catch {
    }
  }
  const seeded = INITIAL_INVENTORY_ITEMS.map(normalizeInventoryRecord)
  return seeded
}

export function saveInventoryRecords(records) {
  const normalized = Array.isArray(records) ? records.map(normalizeInventoryRecord) : []
  localStorage.setItem(INVENTORY_STORAGE_KEY, JSON.stringify(normalized))
  notifyInventoryUpdated()
}

export function fetchAvailableInventoryForService(serviceType = null) {
  const normalizedService = serviceType
    ? mapHardwareCategoryToServiceType('', serviceType)
    : null
  return fetchInventoryRecords().filter((item) => {
    if (!isInventoryDeviceAvailable(item)) return false
    if (!normalizedService) return true
    return item.serviceType === normalizedService
  })
}

export function findInventoryDeviceBySerialOrMac(serialNumber, macAddress = '') {
  const targetSerial = String(serialNumber || '').trim().toUpperCase()
  const targetMac = String(macAddress || '').trim().toUpperCase()
  const records = fetchInventoryRecords()
  if (targetSerial) {
    const bySerial = records.find((item) => item.serialNumber === targetSerial || item.id.toUpperCase() === targetSerial)
    if (bySerial) return bySerial
  }
  if (targetMac) {
    return records.find((item) => item.macAddress === targetMac) || null
  }
  return null
}

export function addInventoryDevice(deviceData = {}) {
  const records = fetchInventoryRecords()
  const serialNumber = String(deviceData.serialNumber || '').trim().toUpperCase()
  const macAddress = String(deviceData.macAddress || '').trim().toUpperCase()
  const model = String(deviceData.model || '').trim()

  if (!model || !serialNumber || !macAddress) {
    throw new Error('Model, Serial Number, and MAC Address are required to register hardware.')
  }

  const duplicate = records.find(
    (item) =>
      item.serialNumber === serialNumber ||
      item.id.toUpperCase() === serialNumber ||
      item.macAddress === macAddress
  )
  if (duplicate) {
    throw new Error('Serial Number or MAC Address already exists in warehouse inventory.')
  }

  const warehouse = WAREHOUSE_LOCATIONS.find((w) => w.code === deviceData.warehouseCode)
  const newItem = normalizeInventoryRecord({
    id: `EQ-${Date.now().toString().slice(-6)}`,
    model,
    category: deviceData.category || 'ONT',
    serialNumber,
    macAddress,
    warehouseCode: deviceData.warehouseCode || 'HUB-HN-01',
    warehouseName: warehouse ? warehouse.name : 'Central Hub Depot',
    currentLocation: warehouse ? warehouse.name : 'Central Hub Depot',
    ouiVendor: deviceData.ouiVendor || model.split(' ')[0] || 'Nexus Carrier',
    specs: deviceData.specs || 'Carrier Grade Subscriber CPE',
    batchPo: deviceData.batchPo || 'PO#2026-NX-01',
    status: 'IN_STOCK',
    condition: 'NEW_A_GRADE',
    firmware: 'NX-FW-v4.8.2',
    intakeDate: new Date().toISOString().slice(0, 10),
    assignedOrderId: null,
    contractAccount: null,
    assignedCustomer: null,
    customerName: 'Unassigned (-)',
  })

  const updated = [newItem, ...records]
  saveInventoryRecords(updated)
  return { device: newItem, items: updated }
}

export function assignInventoryDeviceToOrder({
  deviceId = '',
  serialNumber = '',
  macAddress = '',
  orderId,
  accountId,
  customerName,
}) {
  const records = fetchInventoryRecords()
  const cleanSerial = String(serialNumber || '').trim().toUpperCase()
  const cleanMac = String(macAddress || '').trim().toUpperCase()

  const index = records.findIndex(
    (item) =>
      (deviceId && item.id === deviceId) ||
      (cleanSerial && (item.serialNumber === cleanSerial || item.id.toUpperCase() === cleanSerial)) ||
      (cleanMac && item.macAddress === cleanMac)
  )

  if (index === -1) {
    throw new Error(
      `Hardware S/N "${cleanSerial || deviceId}" was not found in warehouse inventory. Select an IN_STOCK unit or register it in Admin Hardware & Inventory first.`
    )
  }

  const target = records[index]
  if (!isInventoryDeviceAvailable(target)) {
    const holder = target.assignedOrderId
      ? ` (assigned to Order ${target.assignedOrderId})`
      : target.contractAccount
      ? ` (assigned to Account ${target.contractAccount})`
      : ''
    throw new Error(
      `Hardware unit ${target.serialNumber} cannot be assigned because its status is ${target.status}${holder}.`
    )
  }

  if (cleanMac && target.macAddress && target.macAddress !== cleanMac) {
    const macConflict = records.some(
      (item, idx) => idx !== index && item.macAddress === cleanMac && !isInventoryDeviceAvailable(item)
    )
    if (macConflict) {
      throw new Error(`MAC Address ${cleanMac} is already assigned to another active circuit.`)
    }
  }

  const assignedDate = new Date().toISOString().slice(0, 10)
  const resolvedCustomer = String(customerName || 'Enterprise Subscriber').trim()
  const updatedRecord = normalizeInventoryRecord({
    ...target,
    macAddress: cleanMac || target.macAddress,
    status: 'ASSIGNED',
    assignedOrderId: orderId,
    contractAccount: accountId,
    assignedCustomer: resolvedCustomer,
    customerName: resolvedCustomer,
    assignedDate,
    currentLocation: `Customer Site - ${resolvedCustomer}`,
  })

  const updated = [...records]
  updated[index] = updatedRecord
  saveInventoryRecords(updated)
  return { device: updatedRecord, items: updated }
}

export function toggleInventoryFaultyStatus(deviceId) {
  const records = fetchInventoryRecords()
  const index = records.findIndex((item) => item.id === deviceId || item.serialNumber === deviceId)
  if (index === -1) {
    throw new Error(`Hardware unit ${deviceId} not found in inventory.`)
  }
  const target = records[index]
  if (target.status === 'ASSIGNED' || target.status === 'DEPLOYED') {
    throw new Error(
      `Cannot mark ${target.serialNumber} as RMA while it is ${target.status} on an active subscriber circuit.`
    )
  }
  const nextStatus = target.status === 'FAULTY' ? 'IN_STOCK' : 'FAULTY'
  const updated = [...records]
  updated[index] = normalizeInventoryRecord({ ...target, status: nextStatus })
  saveInventoryRecords(updated)
  return { device: updated[index], items: updated }
}

/** Flag a subscriber-assigned hardware unit as damaged for CN17 replacement surcharge assessment. */
export function reportAssignedHardwareDamaged(
  deviceIdOrSerial,
  { reason = 'Physical / Electrical CPE Damage', damageFeeUSD = null } = {}
) {
  const records = fetchInventoryRecords()
  const cleanKey = String(deviceIdOrSerial || '').trim().toUpperCase()
  const index = records.findIndex(
    (item) => item.id.toUpperCase() === cleanKey || item.serialNumber.toUpperCase() === cleanKey
  )
  if (index === -1) {
    throw new Error(`Hardware unit ${deviceIdOrSerial} not found in inventory.`)
  }
  const target = records[index]
  const defaultFeeByCat = { ONT: 85.0, ROUTER: 220.0, VOIP: 180.0, MODEM: 65.0 }
  const resolvedFee =
    damageFeeUSD !== null && damageFeeUSD !== undefined && Number.isFinite(Number(damageFeeUSD))
      ? Number(Number(damageFeeUSD).toFixed(2))
      : defaultFeeByCat[target.category] || 100.0

  const updated = [...records]
  updated[index] = normalizeInventoryRecord({
    ...target,
    status: 'DAMAGED',
    damageReason: reason,
    damageFeeUSD: resolvedFee,
    damageReportedAt: new Date().toISOString().slice(0, 10),
  })
  saveInventoryRecords(updated)
  return { device: updated[index], items: updated }
}

export function fetchDispatchOrders() {
  const local = localStorage.getItem(DISPATCH_STORAGE_KEY)
  if (local !== null) {
    try {
      const parsed = JSON.parse(local)
      if (Array.isArray(parsed)) return parsed
    } catch {
    }
  }
  return INITIAL_DISPATCH_ORDERS
}

export function saveDispatchOrders(orders) {
  localStorage.setItem(DISPATCH_STORAGE_KEY, JSON.stringify(orders))
  notifyInventoryUpdated()
}
